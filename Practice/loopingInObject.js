// Loop in Object

const person = {
  name: "John",
  age: 30,
  city: "New York",
};

const keysOfPerson = Object.keys(person);
console.log(keysOfPerson); // Output: [ 'name', 'age', 'city' ]

const valuesOfPerson = Object.values(person);
console.log(valuesOfPerson); // Output: [ 'John', 30, 'New York' ]